export function pixelIcon(name) {
  const { palette, rows } = ICONS[name]
  const cells = rows.flatMap((row, y) => [...row].map((key, x) => palette[key] ? `<rect x="${x}" y="${y}" width="1.02" height="1.02" fill="${palette[key]}"/>` : ''))
  return `<svg viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${cells.join('')}</svg>`
}
